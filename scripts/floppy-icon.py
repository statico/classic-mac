assert len(G) == 32 and all(len(r) == 32 for r in G), [len(r) for r in G]
paths = []
for ch, fill in FILL.items():
    d = ''.join(f'M{m.start()} {y}h{len(m.group())}v1h-{len(m.group())}z' for y, row in enumerate(G) for m in re.finditer(re.escape(ch) + '+', row))
    paths.append(f'<path fill="{fill}" d="{d}"/>')
print(''.join(paths))
